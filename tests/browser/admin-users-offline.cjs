const { chromium } = require('playwright-core');
const assert = require('node:assert/strict');
const { execFileSync } = require('node:child_process');
const fs = require('node:fs');
const os = require('node:os');
const path = require('node:path');
const { pathToFileURL } = require('node:url');
const root = path.resolve(__dirname, '../..');
const dir = fs.mkdtempSync(path.join(os.tmpdir(), 'upvan-admin-ui-'));
const artifacts = process.argv[2];
if (artifacts) fs.mkdirSync(artifacts, { recursive: true });
let browser;
(async () => {
  const html = execFileSync(path.join(root, '.runtime/php84/php.exe'), ['-n', path.join(__dirname, 'render-admin-users-fixture.php')], { cwd: root, encoding: 'utf8' });
  const assets = pathToFileURL(path.join(root, 'public') + path.sep).href + 'assets/';
  const file = path.join(dir, 'admin-users.html');
  fs.writeFileSync(file, html.replace(/((?:href|src)=["'])\/assets\//g, `$1${assets}`));
  browser = await chromium.launch({ channel: 'chrome', headless: true });
  const page = await browser.newPage({ reducedMotion: 'reduce' });
  const errors = [];
  page.on('pageerror', e => errors.push(e.message));
  for (const width of [360, 375, 768, 1440, 812]) {
    await page.setViewportSize({ width, height: width === 812 ? 375 : 960 });
    await page.goto(pathToFileURL(file).href);
    assert.equal(await page.locator('h1').innerText(), 'จัดการบัญชีผู้ใช้');
    assert.equal(await page.locator('tbody tr').count(), 2);
    assert.equal(await page.locator('tbody tr').first().locator('form').count(), 0, 'protected admin1 has no mutation form');
    assert.equal(await page.locator('.admin-users-table time').count(), 0, 'created date is absent from main table');
    assert.equal(await page.locator('[data-add-role]').count(), 0);
    assert(!(await page.locator('body').innerText()).includes('Action ที่เตรียมไว้'));
    assert(!(await page.locator('body').innerText()).includes('รีเซ็ตรหัสผ่าน'));
    assert.equal(await page.locator('.admin-users-table a[href*="history="]').count(), 2, 'each account has its own history action');
    assert(await page.locator('.admin-users-table').evaluate(el => el.scrollWidth <= el.clientWidth + 1), 'account table needs no horizontal scroll');
    assert.equal(await page.locator('[data-dialog-open],dialog,[data-role-editor]').count(), 0, 'multi-role management UI removed');
    assert.equal(await page.locator('tbody form [name=reason]').count(), 0, 'role and status forms have no reason field');
    const overflow = await page.evaluate(() => ({ viewport: document.documentElement.clientWidth, width: document.documentElement.scrollWidth,
      elements: [...document.querySelectorAll('main,section,form,fieldset,select,aside')].map(el => ({tag: el.tagName, id:el.id, left:el.getBoundingClientRect().left, width:el.getBoundingClientRect().width})).filter(el => el.left+el.width>document.documentElement.clientWidth+1) }));
    assert(overflow.width <= overflow.viewport + 1, `page must not overflow; table can scroll internally: ${JSON.stringify(overflow)}`);
    if (artifacts && [360, 768, 1440].includes(width)) {
      await page.evaluate(() => scrollTo(0, 0));
      await page.screenshot({ path: path.join(artifacts, `admin-users-${width}.png`), fullPage: true });
    }
    console.log(`PASS: compact Admin layout and one role dropdown at ${width}px without horizontal scroll`);
  }
  await page.evaluate(() => {
    window.__offlineSubmits = [];
    document.addEventListener('submit', event => {
      if (event.defaultPrevented) return;
      event.preventDefault();
      window.__offlineSubmits.push(Object.fromEntries(new FormData(event.target)));
      window.__offlineSubmits.at(-1).allRoles = new FormData(event.target).getAll('roles[]');
    });
  });
  const create = page.locator('[data-account-create]');
  assert.deepEqual(await create.locator('[name=role] option').evaluateAll(options => options.map(o => o.value)), ['requester', 'vehicle_officer', 'approver', 'admin']);
  assert.equal(await create.locator('[name=role]').inputValue(), 'requester');
  assert.equal(await create.locator('[name=reason]').count(), 0);
  await create.locator('[name=username]').fill('fixture.new');
  await create.locator('[name=email]').fill('new@example.test');
  await create.locator('[name=display_name]').fill('Fixture');
  await create.locator('[name=password]').fill('dummy-password');
  await create.locator('[name=password_confirmation]').fill('mismatch');
  await create.locator('button[type=submit]').click();
  assert.equal(await create.locator('[name=password_confirmation]').evaluate(el => el.validity.customError), true);
  assert.equal(await page.locator('.swal2-popup').count(), 0);
  console.log('PASS: client password confirmation rejects mismatch');
  await create.locator('[name=password_confirmation]').fill('dummy-password');
  await create.locator('button[type=submit]').click();
  await page.locator('.swal2-popup').waitFor();
  assert.equal(await page.locator('.swal2-confirm').evaluate(el => getComputedStyle(el).backgroundColor), 'rgb(81, 45, 109)');
  await page.locator('.swal2-cancel').click();
  await page.locator('.swal2-popup').waitFor({ state: 'hidden' });
  assert.equal(await page.evaluate(() => window.__offlineSubmits.length), 0);
  console.log('PASS: themed SweetAlert cancellation sends no request');
  await create.locator('button[type=submit]').click();
  await page.locator('.swal2-confirm').click();
  await page.locator('.swal2-popup').waitFor({ state: 'hidden' });
  assert.equal(await page.evaluate(() => window.__offlineSubmits.length), 1);
  assert.equal(await page.evaluate(() => window.__offlineSubmits[0].role), 'requester');
  assert.equal(await page.evaluate(() => window.__offlineSubmits[0].action), 'create');
  console.log('PASS: confirmed form uses existing POST action and Requester default (submission intercepted offline)');
  await create.locator('[name=role]').selectOption('admin');
  await create.locator('button[type=submit]').click();
  await page.locator('.swal2-confirm').click();
  await page.locator('.swal2-popup').waitFor({ state: 'hidden' });
  assert.equal(await page.evaluate(() => window.__offlineSubmits[1].role), 'admin');
  console.log('PASS: Admin create form offers all four roles and requires no reason');
  const primaryForm = page.locator('[data-primary-role-editor]');
  assert.equal(await primaryForm.locator('select').count(), 1);
  assert.equal(await primaryForm.locator('select').inputValue(), 'requester');
  await primaryForm.locator('select').selectOption('approver');
  await primaryForm.getByRole('button', { name: 'บันทึก', exact: true }).click();
  assert((await page.locator('.swal2-html-container').innerText()).includes('ถอดสิทธิ์: ผู้ขอใช้รถ'));
  await page.locator('.swal2-confirm').click();
  await page.locator('.swal2-popup').waitFor({ state: 'hidden' });
  assert.equal(await page.evaluate(() => window.__offlineSubmits[2].action), 'primary_role');
  assert.equal(await page.evaluate(() => window.__offlineSubmits[2].previous_role), 'requester');
  assert.equal(await page.evaluate(() => window.__offlineSubmits[2].primary_role), 'approver');
  assert.deepEqual(await page.evaluate(() => window.__offlineSubmits[2].allRoles), [], 'retained roles are resolved by Backend, not hidden client fields');
  console.log('PASS: primary dropdown confirms single-role replacement without posting other roles');
  const statusForm = page.locator('form').filter({ has: page.locator('input[name=action][value=status]') });
  assert.equal(await statusForm.locator('[name=reason]').count(), 0);
  await statusForm.locator('button[type=submit]').click();
  const statusConfirmation = await page.locator('.swal2-html-container').innerText();
  assert(statusConfirmation.includes('เปลี่ยนแปลง') && !statusConfirmation.includes('เหตุผล'));
  await page.locator('.swal2-confirm').click();
  await page.locator('.swal2-popup').waitFor({ state: 'hidden' });
  assert.equal(await page.evaluate(() => window.__offlineSubmits.length), 4);
  assert.equal(await page.evaluate(() => window.__offlineSubmits[3].action), 'status');
  assert.equal(await page.evaluate(() => Object.hasOwn(window.__offlineSubmits[3], 'reason')), false);
  console.log('PASS: account status change confirms and submits without a reason');
  const multiHtml = execFileSync(path.join(root, '.runtime/php84/php.exe'), ['-n', path.join(__dirname, 'render-admin-users-fixture.php'), 'multiple-roles'], { cwd: root, encoding: 'utf8' });
  const multiFile = path.join(dir, 'multiple-roles.html');
  fs.writeFileSync(multiFile, multiHtml.replace(/((?:href|src)=["'])\/assets\//g, `$1${assets}`));
  await page.goto(pathToFileURL(multiFile).href);
  assert.equal(await page.locator('[data-primary-role-editor] select').isDisabled(), true);
  assert((await page.locator('body').innerText()).includes('กรุณาตรวจสอบก่อนเปลี่ยนสิทธิ์'));
  assert.equal(await page.locator('dialog,[data-dialog-open],[data-role-editor]').count(), 0);
  console.log('PASS: existing multi-role account is flagged and cannot be edited through one-role dropdown');
  const historyHtml = execFileSync(path.join(root, '.runtime/php84/php.exe'), ['-n', path.join(__dirname, 'render-admin-users-fixture.php'), 'history'], { cwd: root, encoding: 'utf8' });
  const historyFile = path.join(dir, 'history.html');
  fs.writeFileSync(historyFile, historyHtml.replace(/((?:href|src)=["'])\/assets\//g, `$1${assets}`));
  for (const width of [360, 768, 1440]) {
    await page.setViewportSize({ width, height: 960 });
    await page.goto(pathToFileURL(historyFile).href);
    const history = page.locator('#user-history');
    assert((await history.innerText()).includes('10/11/2026 04:05'));
    assert((await history.innerText()).includes('10/11/2026 07:00'));
    assert((await history.innerText()).includes('#101'));
    assert((await history.innerText()).includes('เจ้าหน้าที่รถ'));
    assert((await history.innerText()).includes('ระงับบัญชี'));
    assert(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 1));
  }
  console.log('PASS: account history renders dates, actor and old/new values responsively (offline fixture only)');
  assert.deepEqual(errors, []);
  console.log('PASS: Admin UI offline browser checks; fixture HTML only, no web server or database');
})().catch(e => { console.error(e); process.exitCode = 1; }).finally(async () => {
  if (browser) await browser.close();
  for (const file of fs.readdirSync(dir)) fs.unlinkSync(path.join(dir, file));
  fs.rmdirSync(dir);
});
